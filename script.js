const EMAIL_ADDRESS = "djvantmusic@gmail.com";
let currentLang = localStorage.getItem("lg_lang") || "sl";

function buildMailtoHref(lang, type) {
  const tpl = (mailtoTemplates[lang] && mailtoTemplates[lang][type]) || mailtoTemplates.sl.general;
  return `mailto:${EMAIL_ADDRESS}?subject=${encodeURIComponent(tpl.subject)}&body=${encodeURIComponent(tpl.body)}`;
}

function applyLanguage(lang) {
  if (!translations[lang]) lang = "sl";
  currentLang = lang;
  localStorage.setItem("lg_lang", lang);

  document.documentElement.lang = lang;
  document.documentElement.setAttribute("data-lang", lang);
  document.title = translations[lang].page_title;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (translations[lang][key]) {
      el.innerHTML = translations[lang][key];
    }
  });

  document.querySelectorAll("[data-mailto]").forEach((link) => {
    const type = link.getAttribute("data-mailto");
    link.setAttribute("href", buildMailtoHref(lang, type));
  });

  document.querySelectorAll("[data-set-lang]").forEach((btn) => {
    const isMatch = btn.getAttribute("data-set-lang") === lang;
    btn.classList.toggle("active", isMatch);
    btn.setAttribute("aria-pressed", isMatch ? "true" : "false");
  });
}

document.addEventListener("DOMContentLoaded", () => {
  applyLanguage(currentLang);

  // Language switcher
  document.querySelectorAll("[data-set-lang]").forEach((btn) => {
    btn.addEventListener("click", () => {
      applyLanguage(btn.getAttribute("data-set-lang"));
    });
  });

  // Copy email button
  const copyBtn = document.getElementById("copyEmailBtn");
  const copyBtnText = document.getElementById("copyBtnText");
  if (copyBtn && copyBtnText) {
    copyBtn.addEventListener("click", async () => {
      try {
        await navigator.clipboard.writeText(EMAIL_ADDRESS);
        copyBtnText.textContent = translations[currentLang].copied_email;
        setTimeout(() => {
          copyBtnText.textContent = translations[currentLang].copy_email;
        }, 2200);
      } catch {
        window.location.href = `mailto:${EMAIL_ADDRESS}`;
      }
    });
  }

  // Mobile navigation toggle
  const mobileMenuBtn = document.getElementById("mobileMenuBtn");
  const mainNav = document.querySelector(".main-nav");
  if (mobileMenuBtn && mainNav) {
    mobileMenuBtn.addEventListener("click", () => {
      const isOpen = mainNav.classList.toggle("open");
      mobileMenuBtn.setAttribute("aria-expanded", isOpen ? "true" : "false");
    });

    mainNav.querySelectorAll("a").forEach((link) => {
      link.addEventListener("click", () => {
        mainNav.classList.remove("open");
        mobileMenuBtn.setAttribute("aria-expanded", "false");
      });
    });
  }

  // Gallery category filter
  const filterBtns = document.querySelectorAll(".filter-btn");
  const galleryItems = document.querySelectorAll(".m-item");
  filterBtns.forEach((btn) => {
    btn.addEventListener("click", () => {
      const filter = btn.getAttribute("data-filter");
      filterBtns.forEach((b) => b.classList.remove("active"));
      btn.classList.add("active");

      galleryItems.forEach((item) => {
        const cat = item.getAttribute("data-category");
        if (filter === "all" || cat === filter) {
          item.classList.remove("hidden");
        } else {
          item.classList.add("hidden");
        }
      });
    });
  });

  // Lightbox modal for gallery photos (with Prev/Next arrows, keyboard & touch swipe)
  const lightbox = document.getElementById("lightbox");
  const lightboxImg = document.getElementById("lightboxImg");
  const lightboxCaption = document.getElementById("lightboxCaption");
  const lightboxCounter = document.getElementById("lightboxCounter");
  const lightboxClose = document.getElementById("lightboxClose");
  const lightboxPrev = document.getElementById("lightboxPrev");
  const lightboxNext = document.getElementById("lightboxNext");

  if (lightbox && lightboxImg && lightboxClose) {
    let activeList = [];
    let currentIndex = 0;

    const getVisibleGalleryItems = () =>
      Array.from(galleryItems).filter((item) => !item.classList.contains("hidden"));

    const renderLightboxItem = (index) => {
      if (!activeList.length) return;
      currentIndex = (index + activeList.length) % activeList.length;
      const item = activeList[currentIndex];
      const fullSrc = item.getAttribute("data-full");
      const titleEl = item.querySelector("strong");
      lightboxImg.src = fullSrc;
      lightboxImg.alt = titleEl ? titleEl.textContent : "";
      if (lightboxCaption) {
        lightboxCaption.textContent = titleEl ? titleEl.textContent : "";
      }
      if (lightboxCounter) {
        lightboxCounter.textContent = `${currentIndex + 1} / ${activeList.length}`;
      }
    };

    galleryItems.forEach((item) => {
      item.addEventListener("click", () => {
        activeList = getVisibleGalleryItems();
        const idx = activeList.indexOf(item);
        renderLightboxItem(idx >= 0 ? idx : 0);
        lightbox.classList.add("open");
        lightbox.setAttribute("aria-hidden", "false");
      });
    });

    const showPrev = (e) => {
      if (e) e.stopPropagation();
      renderLightboxItem(currentIndex - 1);
    };

    const showNext = (e) => {
      if (e) e.stopPropagation();
      renderLightboxItem(currentIndex + 1);
    };

    const closeLightbox = () => {
      lightbox.classList.remove("open");
      lightbox.setAttribute("aria-hidden", "true");
      lightboxImg.src = "";
    };

    if (lightboxPrev) lightboxPrev.addEventListener("click", showPrev);
    if (lightboxNext) lightboxNext.addEventListener("click", showNext);
    lightboxClose.addEventListener("click", closeLightbox);

    lightbox.addEventListener("click", (e) => {
      if (e.target === lightbox) closeLightbox();
    });

    document.addEventListener("keydown", (e) => {
      if (!lightbox.classList.contains("open")) return;
      if (e.key === "Escape") closeLightbox();
      if (e.key === "ArrowLeft") showPrev();
      if (e.key === "ArrowRight") showNext();
    });

    // Touch swipe support on mobile
    let touchStartX = 0;
    lightbox.addEventListener(
      "touchstart",
      (e) => {
        if (e.changedTouches && e.changedTouches.length > 0) {
          touchStartX = e.changedTouches[0].screenX;
        }
      },
      { passive: true }
    );

    lightbox.addEventListener(
      "touchend",
      (e) => {
        if (e.changedTouches && e.changedTouches.length > 0) {
          const diffX = e.changedTouches[0].screenX - touchStartX;
          if (Math.abs(diffX) > 45) {
            if (diffX < 0) {
              showNext();
            } else {
              showPrev();
            }
          }
        }
      },
      { passive: true }
    );
  }

  // Mobile "Show All Photos" toggle
  const galleryMoreBtn = document.getElementById("galleryMoreBtn");
  const galleryMoreText = document.getElementById("galleryMoreText");
  const galleryGrid = document.getElementById("galleryGrid");
  if (galleryMoreBtn && galleryMoreText && galleryGrid) {
    galleryMoreBtn.addEventListener("click", () => {
      const expanded = galleryGrid.classList.toggle("expanded-mobile");
      galleryMoreText.setAttribute("data-i18n", expanded ? "show_less_photos" : "show_all_photos");
      galleryMoreText.textContent = expanded
        ? translations[currentLang].show_less_photos
        : translations[currentLang].show_all_photos;
    });
  }

  // Auto-hide floating contact dock when user is already at #rezervacija section
  const floatingDock = document.getElementById("floatingDock");
  const bookingSection = document.getElementById("rezervacija");
  if (floatingDock && bookingSection && "IntersectionObserver" in window) {
    const observer = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          floatingDock.classList.toggle("dock-hidden", entry.isIntersecting);
        });
      },
      { threshold: 0.25 }
    );
    observer.observe(bookingSection);
  }
});
